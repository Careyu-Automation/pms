const { pdf } = require('./timeExport');
const dailyFormat = require('./emailReport.dailyFormat');

function escapeXml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function linesOf(snapshot) {
  const lines = [
    'Care Yu Automation',
    'Project Hub',
    snapshot.title,
    `Period ${snapshot.period.from} to ${snapshot.period.to}`,
    `Generated ${snapshot.generatedAt}`,
    '',
  ];
  (snapshot.kpis || []).forEach((item) => lines.push(`${item.label}: ${item.value}`));
  lines.push('');
  if (snapshot.type === 'DAILY_WORK') {
    const groups = dailyFormat.groupByEmployee(snapshot.dailyRows || []);
    if (!groups.length) {
      lines.push('No daily work updates found for the selected date.');
    } else {
      groups.forEach((group) => {
        lines.push(group.employeeName);
        lines.push(dailyFormat.reportColumns().join(' | '));
        group.rows.forEach((row) => {
          lines.push(dailyFormat.reportRowCells(row).map((cell) => String(cell ?? '')).join(' | '));
        });
        lines.push('');
      });
    }
  } else {
    (snapshot.sections || []).forEach((section) => {
      lines.push(section.title);
      if (section.columns) lines.push(section.columns.join(' | '));
      (section.rows || []).forEach((row) => lines.push(row.map((cell) => String(cell ?? '')).join(' | ')));
      lines.push('');
    });
    if (!(snapshot.sections || []).some((section) => (section.rows || []).length)) {
      lines.push('No records for this period.');
    }
  }
  lines.push('Generated by Care Yu Automation Project Hub');
  return lines;
}

function pdfBuffer(snapshot) {
  return pdf(snapshot.title, linesOf(snapshot));
}

function excelBuffer(snapshot) {
  const sheets = [];
  const meta = [
    ['Report', snapshot.title],
    ['Type', snapshot.typeLabel || snapshot.type],
    ['From', snapshot.period.from],
    ['To', snapshot.period.to],
    ['Generated', snapshot.generatedAt],
    ...((snapshot.kpis || []).map((item) => [item.label, item.value])),
  ];
  sheets.push(sheet('Summary', ['Field', 'Value'], meta));
  if (snapshot.type === 'DAILY_WORK') {
    const rows = (snapshot.dailyRows || []).length
      ? dailyFormat.groupByEmployee(snapshot.dailyRows).flatMap((group) => group.rows.map((row) => dailyFormat.excelFlatRow(row)))
      : [['No daily work updates found for the selected date.']];
    sheets.push(sheet('Daily Work Updates', ['Employee', ...dailyFormat.reportColumns()], rows));
  } else {
    (snapshot.sections || []).forEach((section, index) => {
      const name = String(section.title || `Sheet ${index + 1}`).slice(0, 28);
      const rows = (section.rows || []).length
        ? section.rows
        : [['No records for this period.']];
      sheets.push(sheet(name, section.columns || ['Value'], rows));
    });
  }
  return Buffer.from(`<?xml version="1.0"?>
<?mso-application progid="Excel.Sheet"?>
<Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet" xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet" xmlns:x="urn:schemas-microsoft-com:office:excel">
${sheets.join('')}
</Workbook>`, 'utf8');
}

function sheet(name, columns, rows) {
  const widths = (columns || []).map(() => '<Column ss:AutoFitWidth="1" ss:Width="140"/>').join('');
  const body = [columns, ...rows].map((line, index) => {
    const cells = line.map((cell) => `<Cell><Data ss:Type="String">${escapeXml(cell)}</Data></Cell>`).join('');
    return `<Row${index === 0 ? ' ss:StyleID="Header"' : ''}>${cells}</Row>`;
  }).join('');
  return `<Worksheet ss:Name="${escapeXml(name)}"><Table>${widths}${body}</Table>
<WorksheetOptions xmlns="urn:schemas-microsoft-com:office:excel"><FreezePanes/><FrozenNoSplit/><SplitHorizontal>1</SplitHorizontal><TopRowBottomPane>1</TopRowBottomPane></WorksheetOptions>
</Worksheet>`;
}

function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

function textHtml(value) {
  return escapeHtml(value).replace(/\r?\n/g, '<br>');
}

function prettyDate(iso) {
  const text = String(iso || '').slice(0, 10);
  const [year, month, day] = text.split('-').map(Number);
  if (!year || !month || !day) return text;
  return new Intl.DateTimeFormat('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }).format(new Date(year, month - 1, day));
}

function reportStamp(iso) {
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const [year, month, day] = String(iso || '').slice(0, 10).split('-').map(Number);
  if (!year || !month || !day) return '';
  return `${String(day).padStart(2, '0')}-${months[month - 1]}-${year}`;
}

function statusBadgeHtml(status) {
  const label = dailyFormat.statusLabel(status);
  const tone = dailyFormat.statusBadgeStyle(status);
  return `<span style="display:inline-block;padding:4px 10px;border-radius:4px;background:${tone.bg};color:${tone.color};border:1px solid ${tone.border};font-size:12px;font-weight:700;line-height:1.2;white-space:nowrap;word-break:keep-all;overflow-wrap:normal">${escapeHtml(label)}</span>`;
}

function cellHtml(content, options = {}) {
  const {
    wrap = false,
    width,
    minWidth,
    maxWidth,
    align = 'left',
    blocked = false,
  } = options;
  const style = [
    'padding:10px 12px',
    'border:1px solid #d7e2ee',
    'font-size:13px',
    'line-height:1.45',
    'vertical-align:top',
    'color:#102033',
    `text-align:${align}`,
    blocked ? 'background:#fffaf0' : 'background:#ffffff',
    wrap
      ? 'white-space:normal;overflow-wrap:break-word;word-break:normal'
      : 'white-space:nowrap;overflow-wrap:normal;word-break:keep-all',
    width ? `width:${width}` : '',
    minWidth ? `min-width:${minWidth}` : '',
    maxWidth ? `max-width:${maxWidth}` : '',
  ].filter(Boolean).join(';');
  return `<td style="${style}">${content}</td>`;
}

function dailyWorkEmail(snapshot) {
  const period = snapshot.period || {};
  const when = reportStamp(period.from) || prettyDate(period.from);
  const shift = snapshot.shift === 'Evening' ? 'Evening' : snapshot.shift === 'Morning' ? 'Morning' : 'Full day';
  const rows = snapshot.dailyRows || [];
  const groups = dailyFormat.groupByEmployee(rows);
  const columns = dailyFormat.reportColumns();
  const widths = {
    Project: { width: '18%', minWidth: '120px' },
    'Work Description': { width: '34%', minWidth: '180px', maxWidth: '360px', wrap: true },
    Status: { width: '12%', minWidth: '110px' },
    Dependencies: { width: '14%', minWidth: '110px', wrap: true },
    Priority: { width: '9%', minWidth: '80px' },
    'Next Action / Remarks': { width: '13%', minWidth: '110px', wrap: true },
  };
  const head = columns.map((column) => {
    const meta = widths[column] || {};
    const style = [
      'padding:10px 12px',
      'border:1px solid #bfcfe3',
      'background:#0356c5',
      'color:#ffffff',
      'font-size:12px',
      'font-weight:700',
      'text-align:left',
      'white-space:nowrap',
      meta.width ? `width:${meta.width}` : '',
      meta.minWidth ? `min-width:${meta.minWidth}` : '',
    ].filter(Boolean).join(';');
    return `<th style="${style}">${escapeHtml(column)}</th>`;
  }).join('');

  const groupsHtml = groups.map((group) => {
    const body = group.rows.map((row) => {
      const blocked = String(row.status || '').toUpperCase() === 'BLOCKED';
      const cells = [
        cellHtml(textHtml(row.projectName || 'No project'), { ...widths.Project, blocked }),
        cellHtml(textHtml(dailyFormat.workDescription(row)), { ...widths['Work Description'], blocked }),
        cellHtml(statusBadgeHtml(row.status), { ...widths.Status, blocked }),
        cellHtml(textHtml(dailyFormat.dependencyText(row)), { ...widths.Dependencies, blocked }),
        cellHtml(textHtml(dailyFormat.priorityLabel(row.priority)), { ...widths.Priority, blocked }),
        cellHtml(textHtml(row.nextAction || row.reasonForDelay || '—'), { ...widths['Next Action / Remarks'], blocked }),
      ];
      return `<tr>${cells.join('')}</tr>`;
    }).join('');
    return `
      <div style="margin:0 0 22px">
        <div style="margin:0 0 8px;padding:8px 12px;background:#fff8e1;border-left:4px solid #f1c232;border-radius:0 4px 4px 0">
          <div style="font-size:16px;font-weight:700;color:#021e45;letter-spacing:.01em">${escapeHtml(group.employeeName)}</div>
          <div style="font-size:12px;color:#5b6b80;margin-top:2px">${group.rows.length} update${group.rows.length === 1 ? '' : 's'}</div>
        </div>
        <table role="presentation" cellpadding="0" cellspacing="0" style="width:100%;border-collapse:collapse;border:1px solid #c5d0dc;table-layout:fixed">
          <thead><tr>${head}</tr></thead>
          <tbody>${body}</tbody>
        </table>
      </div>`;
  }).join('');

  const empty = `<p style="margin:12px 0;padding:14px 12px;border:1px solid #d9d9d9;background:#fff8e1;color:#5b5346">No daily work updates were found for ${escapeHtml(when)} (${escapeHtml(shift)}).</p>`;

  return `<!doctype html><html><body style="margin:0;padding:0;background:#f3f6fb;font-family:Calibri,Segoe UI,Arial,sans-serif;color:#102033;font-size:14px;line-height:1.5">
    <div style="max-width:980px;margin:0 auto;background:#ffffff">
      <div style="padding:18px 22px;background:linear-gradient(135deg,#0356c5 0%,#033b88 100%);color:#ffffff">
        <div style="font-size:12px;letter-spacing:.08em;text-transform:uppercase;opacity:.9">CareYu Automation</div>
        <div style="margin-top:4px;font-size:22px;font-weight:700">Daily Work Updates Report</div>
        <div style="margin-top:8px;font-size:14px;opacity:.95">${escapeHtml(shift)} · ${escapeHtml(when)}</div>
      </div>
      <div style="padding:10px 22px;background:#fff8e1;border-bottom:1px solid #f1c232;color:#5b5346;font-size:13px">
        Report date: <strong style="color:#102033">${escapeHtml(when)}</strong>
        &nbsp;·&nbsp; Period: <strong style="color:#102033">${escapeHtml(shift)}</strong>
        &nbsp;·&nbsp; Submitted updates: <strong style="color:#102033">${rows.length}</strong>
        &nbsp;·&nbsp; Employees: <strong style="color:#102033">${groups.length}</strong>
      </div>
      <div style="padding:22px">
        <p style="margin:0 0 12px">Dear Team,</p>
        <p style="margin:0 0 16px">Please find the ${escapeHtml(shift)} Daily Work Updates Report below, grouped by employee.</p>
        ${groups.length ? groupsHtml : empty}
        <p style="margin:20px 0 0">Please review blocked items and follow up on dependencies where needed.</p>
        <p style="margin:16px 0 0">Regards,<br>CareYu Automation<br>Project Hub</p>
      </div>
      <div style="padding:14px 22px;border-top:1px solid #e5effb;color:#5b6b80;font-size:12px;background:#f7fafc">
        Generated by CareYu Automation Project Hub
      </div>
    </div>
  </body></html>`;
}

function htmlEmail(snapshot) {
  if (snapshot.type === 'DAILY_WORK') return dailyWorkEmail(snapshot);
  const kpis = (snapshot.kpis || []).map((item) => `<td style="padding:8px 12px;border:1px solid #e5effb"><div style="color:#5b6b80;font-size:12px">${escapeHtml(item.label)}</div><div style="color:#033b88;font-size:18px;font-weight:700">${escapeHtml(item.value)}</div></td>`).join('');
  const tables = (snapshot.sections || []).map((section) => {
    const head = (section.columns || []).map((column) => `<th style="text-align:left;padding:6px 8px;background:#e5effb;color:#033b88">${escapeHtml(column)}</th>`).join('');
    const body = (section.rows || []).slice(0, 40).map((row) => `<tr>${row.map((cell) => `<td style="padding:6px 8px;border-top:1px solid #e5effb">${escapeHtml(cell)}</td>`).join('')}</tr>`).join('');
    return `<h2 style="font-size:16px;color:#021e45">${escapeHtml(section.title)}</h2><table style="width:100%;border-collapse:collapse;font-size:13px"><thead><tr>${head}</tr></thead><tbody>${body || '<tr><td>No records for this period.</td></tr>'}</tbody></table>`;
  }).join('');
  return `<!doctype html><html><body style="margin:0;background:#f5f8fc;font-family:Segoe UI,Arial,sans-serif;color:#102033">
  <div style="max-width:760px;margin:0 auto;background:#ffffff">
    <div style="background:#0356c5;color:#ffffff;padding:20px 24px">
      <div style="font-size:13px;letter-spacing:.04em">CARE YU AUTOMATION</div>
      <div style="font-size:20px;font-weight:700;margin-top:4px">Project Hub</div>
    </div>
    <div style="padding:24px">
      <h1 style="margin:0 0 6px;font-size:22px;color:#021e45">${escapeHtml(snapshot.title)}</h1>
      <p style="margin:0 0 16px;color:#5b6b80">${escapeHtml(snapshot.typeLabel || '')} · ${escapeHtml(snapshot.period.from)} to ${escapeHtml(snapshot.period.to)}</p>
      <table style="border-collapse:collapse;margin-bottom:16px"><tr>${kpis}</tr></table>
      ${tables}
    </div>
    <div style="padding:16px 24px;color:#5b6b80;font-size:12px;border-top:1px solid #e5effb">Generated by Care Yu Automation Project Hub · ${escapeHtml(snapshot.generatedAt)}</div>
  </div></body></html>`;
}

module.exports = { pdfBuffer, excelBuffer, htmlEmail };
