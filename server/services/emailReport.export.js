const { pdf } = require('./timeExport');

function escapeXml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function linesOf(snapshot) {
  const lines = [
    'Care Yu Automation',
    'Project Hub',
    snapshot.title,
    `Period ${snapshot.period.from} to ${snapshot.period.to}`,
    `Generated ${snapshot.generatedAt}`,
    '',
  ];
  (snapshot.kpis || []).forEach((item) => lines.push(`${item.label}: ${item.value}`));
  lines.push('');
  (snapshot.sections || []).forEach((section) => {
    lines.push(section.title);
    if (section.columns) lines.push(section.columns.join(' | '));
    (section.rows || []).forEach((row) => lines.push(row.map((cell) => String(cell ?? '')).join(' | ')));
    lines.push('');
  });
  if (!(snapshot.sections || []).some((section) => (section.rows || []).length)) {
    lines.push(snapshot.type === 'DAILY_WORK' ? 'No daily work updates found for the selected date.' : 'No records for this period.');
  }
  lines.push('Generated by Care Yu Automation Project Hub');
  return lines;
}

function pdfBuffer(snapshot) {
  return pdf(snapshot.title, linesOf(snapshot));
}

function excelBuffer(snapshot) {
  const sheets = [];
  const meta = [
    ['Report', snapshot.title],
    ['Type', snapshot.typeLabel || snapshot.type],
    ['From', snapshot.period.from],
    ['To', snapshot.period.to],
    ['Generated', snapshot.generatedAt],
    ...((snapshot.kpis || []).map((item) => [item.label, item.value])),
  ];
  sheets.push(sheet('Summary', ['Field', 'Value'], meta));
  (snapshot.sections || []).forEach((section, index) => {
    const name = String(section.title || `Sheet ${index + 1}`).slice(0, 28);
    const rows = (section.rows || []).length
      ? section.rows
      : [[snapshot.type === 'DAILY_WORK' ? 'No daily work updates found for the selected date.' : 'No records for this period.']];
    sheets.push(sheet(name, section.columns || ['Value'], rows));
  });
  return Buffer.from(`<?xml version="1.0"?>
<?mso-application progid="Excel.Sheet"?>
<Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet" xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet" xmlns:x="urn:schemas-microsoft-com:office:excel">
${sheets.join('')}
</Workbook>`, 'utf8');
}

function sheet(name, columns, rows) {
  const widths = (columns || []).map(() => '<Column ss:AutoFitWidth="1" ss:Width="140"/>').join('');
  const body = [columns, ...rows].map((line, index) => {
    const cells = line.map((cell) => `<Cell><Data ss:Type="String">${escapeXml(cell)}</Data></Cell>`).join('');
    return `<Row${index === 0 ? ' ss:StyleID="Header"' : ''}>${cells}</Row>`;
  }).join('');
  return `<Worksheet ss:Name="${escapeXml(name)}"><Table>${widths}${body}</Table>
<WorksheetOptions xmlns="urn:schemas-microsoft-com:office:excel"><FreezePanes/><FrozenNoSplit/><SplitHorizontal>1</SplitHorizontal><TopRowBottomPane>1</TopRowBottomPane></WorksheetOptions>
</Worksheet>`;
}

const DAILY_WRAP = new Set(['Work Title', 'Description', 'Project', 'Team', 'Work Type', 'Outstanding blockers or dependencies', 'Next actions requiring attention']);

function cellStyle(column, index) {
  const wrap = DAILY_WRAP.has(column);
  return [
    'padding:10px 12px',
    'border:1px solid #d7e2ee',
    'font-size:13px',
    'line-height:1.45',
    'vertical-align:top',
    'color:#102033',
    wrap ? 'white-space:normal;overflow-wrap:anywhere;word-break:break-word;min-width:140px;max-width:280px' : 'white-space:nowrap',
    index % 2 === 1 ? 'background:#f7fafc' : 'background:#ffffff',
  ].join(';');
}

function textHtml(value) {
  return escapeHtml(value).replace(/\r?\n/g, '<br>');
}

function prettyDate(iso) {
  const text = String(iso || '').slice(0, 10);
  const [year, month, day] = text.split('-').map(Number);
  if (!year || !month || !day) return text;
  return new Intl.DateTimeFormat('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }).format(new Date(year, month - 1, day));
}

function dailyWorkEmail(snapshot) {
  const period = snapshot.period || {};
  const when = prettyDate(period.from);
  const section = (snapshot.sections || [])[0] || { columns: [], rows: [] };
  const columns = section.columns || [];
  const head = columns.map((column) => `<th style="padding:10px 12px;border:1px solid #d7e2ee;background:#0356c5;color:#ffffff;font-size:12px;font-weight:700;text-align:left;white-space:nowrap">${escapeHtml(column)}</th>`).join('');
  const body = (section.rows || []).map((row, index) => `<tr>${row.map((cell, cellIndex) => `<td style="${cellStyle(columns[cellIndex], index)}">${textHtml(cell)}</td>`).join('')}</tr>`).join('');
  const empty = `<p style="margin:12px 0;padding:14px 12px;border:1px solid #d7e2ee;background:#f7fafc;color:#5b6b80">No daily work updates found for the selected date.</p>`;
  const tableHtml = body
    ? `<div style="overflow-x:auto;-webkit-overflow-scrolling:touch"><table role="presentation" cellpadding="0" cellspacing="0" style="width:100%;border-collapse:collapse;border:1px solid #d7e2ee"><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table></div>`
    : empty;
  return `<!doctype html><html><body style="margin:0;padding:0;background:#f5f8fc;font-family:Segoe UI,Arial,sans-serif;color:#102033;font-size:14px;line-height:1.5">
    <div style="max-width:920px;margin:0 auto;background:#ffffff">
      <div style="padding:20px 24px;background:#0356c5;color:#ffffff">
        <div style="font-size:12px;letter-spacing:.08em;text-transform:uppercase">CareYu Automation</div>
        <div style="margin-top:4px;font-size:22px;font-weight:700">Daily Work Report</div>
      </div>
      <div style="padding:24px">
        <p style="margin:0 0 12px">Dear Team,</p>
        <p style="margin:0 0 16px">Please find below the Daily Work Report for <strong>${escapeHtml(when)}</strong>.</p>
        <p style="margin:0 0 16px">The following table lists the work updates recorded.</p>
        ${tableHtml}
        <p style="margin:20px 0 0">Regards,<br>CareYu Automation<br>Project Hub</p>
      </div>
    </div>
  </body></html>`;
}

function htmlEmail(snapshot) {
  if (snapshot.type === 'DAILY_WORK') return dailyWorkEmail(snapshot);
  const kpis = (snapshot.kpis || []).map((item) => `<td style="padding:8px 12px;border:1px solid #e5effb"><div style="color:#5b6b80;font-size:12px">${escapeHtml(item.label)}</div><div style="color:#033b88;font-size:18px;font-weight:700">${escapeHtml(item.value)}</div></td>`).join('');
  const tables = (snapshot.sections || []).map((section) => {
    const head = (section.columns || []).map((column) => `<th style="text-align:left;padding:6px 8px;background:#e5effb;color:#033b88">${escapeHtml(column)}</th>`).join('');
    const body = (section.rows || []).slice(0, 40).map((row) => `<tr>${row.map((cell) => `<td style="padding:6px 8px;border-top:1px solid #e5effb">${escapeHtml(cell)}</td>`).join('')}</tr>`).join('');
    return `<h2 style="font-size:16px;color:#021e45">${escapeHtml(section.title)}</h2><table style="width:100%;border-collapse:collapse;font-size:13px"><thead><tr>${head}</tr></thead><tbody>${body || '<tr><td>No records for this period.</td></tr>'}</tbody></table>`;
  }).join('');
  return `<!doctype html><html><body style="margin:0;background:#f5f8fc;font-family:Segoe UI,Arial,sans-serif;color:#102033">
  <div style="max-width:760px;margin:0 auto;background:#ffffff">
    <div style="background:#0356c5;color:#ffffff;padding:20px 24px">
      <div style="font-size:13px;letter-spacing:.04em">CARE YU AUTOMATION</div>
      <div style="font-size:20px;font-weight:700;margin-top:4px">Project Hub</div>
    </div>
    <div style="padding:24px">
      <h1 style="margin:0 0 6px;font-size:22px;color:#021e45">${escapeHtml(snapshot.title)}</h1>
      <p style="margin:0 0 16px;color:#5b6b80">${escapeHtml(snapshot.typeLabel || '')} · ${escapeHtml(snapshot.period.from)} to ${escapeHtml(snapshot.period.to)}</p>
      <table style="border-collapse:collapse;margin-bottom:16px"><tr>${kpis}</tr></table>
      ${tables}
    </div>
    <div style="padding:16px 24px;color:#5b6b80;font-size:12px;border-top:1px solid #e5effb">Generated by Care Yu Automation Project Hub · ${escapeHtml(snapshot.generatedAt)}</div>
  </div></body></html>`;
}

function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
}

module.exports = { pdfBuffer, excelBuffer, htmlEmail };
