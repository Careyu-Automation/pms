export function getDefaultSections() {
  return Object.fromEntries(navigation.map((group) => [group.id, group.defaultOpen]));
}

export function getModuleRoutes() {
  return navigation.flatMap((group) => group.items.map((item) => ({
    ...item,
    groupId: group.id,
    groupLabel: group.label,
    crumbs: [{ label: group.label }, { label: item.crumb || item.label }],
  })));
}
